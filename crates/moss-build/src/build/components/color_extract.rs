/// Neutral near-black band for iframe covers that declare no color —
/// consistent with extracted bands, which land around 21–25% lightness
/// at low saturation after WCAG darkening.
pub const IFRAME_COVER_FALLBACK: &str = "hsla(0, 0%, 18%, 1)";

/// Resolve a folder card's `--moss-cover-color` for ANY cover type — the
/// single entry point both card renderers (`grid_cells::apply_collection_cards`,
/// `folder_embed`) MUST call, for the same reason they must share
/// `resolve_color_source_path`: per-renderer copies of this ladder drift.
///
/// Ladder:
/// 1. `color=` pipe-attr override — wins for every cover type.
/// 2. By cover type:
///    - Image/Video: scan-cached dominant color, else runtime extraction
///      (pre-existing behavior, unchanged).
///    - Iframe: static page scan (`extract_webpage_color`), else the dark
///      default — an iframe cover ALWAYS yields a color.
///
/// `cover` is the pipe-encoded value as stored on `ChildItemProps.cover`
/// (path already URL-resolved by the caller; attrs re-joined after `|`).
/// `root` is the project root; `None` disables file reads (external URLs,
/// tests) — image covers then resolve to `None`, iframe covers to the
/// fallback.
pub fn resolve_card_color(
    cover: Option<&str>,
    cover_type: Option<CoverType>,
    root: Option<&Path>,
    media_lookup: Option<&MediaDimensionLookup>,
) -> Option<String> {
    let cover = cover?;
    let (path_part, attrs_str) = moss_core::media::split_pipe(cover);

    // Rung 1: author override.
    let attrs = moss_core::media::parse_media_attrs(attrs_str);
    if let Some(raw) = attrs.color.as_deref() {
        if let Some((r, g, b)) = parse_css_color(raw) {
            return Some(darkened_hsla(r, g, b));
        }
        log::warn!("cover color override '{raw}' is not a recognized CSS color; falling back");
    }

    match cover_type {
        Some(CoverType::Iframe) => {
            // Rungs 2–3: static page scan; rung 4: dark default. External
            // URLs and missing files land on the default — an iframe
            // cover always produces a color.
            let scanned = root
                .and_then(|root| {
                    resolve_color_source_path(
                        path_part,
                        root,
                        &crate::moss_paths::MossPaths::new(root).current_ptr(),
                    )
                })
                .and_then(|p| extract_webpage_color(&p));
            Some(scanned.unwrap_or_else(|| IFRAME_COVER_FALLBACK.to_string()))
        }
        _ => {
            // Image/Video: pre-existing behavior, moved verbatim from the
            // two renderers. Cache first (consistent with the
            // SVG-placeholder pipeline, no re-decode), then runtime
            // extraction (partial scans, watch-mode races).
            if let Some(lookup) = media_lookup {
                if let Some(color) = lookup.get_cover_color(path_part) {
                    return Some(color);
                }
            }
            let root = root?;
            let resolved = resolve_color_source_path(
                path_part,
                root,
                &crate::moss_paths::MossPaths::new(root).current_ptr(),
            )?;
            extract_dominant_color(&resolved)
        }
    }
}

