//! Color extraction from images for card backgrounds
//!
//! Extracts the dominant color from cover images to use as card background colors.
//! The extracted color is darkened to guarantee WCAG AA contrast (≥ 4.5:1) against
//! white text, using the W3C relative luminance formula.

use std::path::{Path, PathBuf};

use moss_core::asset_paths;

use crate::build::media::cover::CoverType;
use crate::build::media::dimensions::MediaDimensionLookup;

/// Resolve a cover URL to an on-disk image file that `extract_dominant_color`
/// can read.
///
/// Both folder-card renderers — `render::grid_cells::apply_collection_cards`
/// (inline `:::grid` shortcodes) and `page::generate_children` for
/// `children_style: grid` — MUST call this helper. Keeping the resolution
/// in one place prevents the two paths from drifting apart on video
/// handling (the original bug: one renderer rewrote `.mp4` → `.thumb.jpg`
/// before reading, the other passed `.mp4` straight to `image::open()`,
/// silently failing on every video cover).
///
/// `cover_url` is expected in its post-`PathResolver::resolve_url` form —
/// leading `/`, dir-overrides applied, percent-encoded. This helper decodes it
/// back to the on-disk name; passing an already-decoded URL is harmless
/// (decoding is a no-op when there is no `%`).
///
/// Resolution rules:
/// 1. External URL (`http://…`, `https://…`) → `None`. We don't fetch.
/// 2. Video (`.mp4`, `.mov`, `.webm`, …) → `<output_root>/<stem>.thumb.jpg`,
///    the JPEG poster generated by the FFmpeg pipeline.
/// 3. Image → source root first, output root as fallback.
/// 4. Webpage covers (`.html`) follow the image rule (source root first,
///    output fallback) — `resolve_card_color` reads them as text, not pixels.
///
/// Returning `Some(path)` does not guarantee the file exists; callers pass
/// the result to `extract_dominant_color`, which returns `None` on read
/// failure (treated as "no extracted color, use default styling").
pub fn resolve_color_source_path(
    cover_url: &str,
    source_root: &Path,
    output_root: &Path,
) -> Option<PathBuf> {
    if cover_url.starts_with("http://") || cover_url.starts_with("https://") {
        return None;
    }
    // A URL is not a path. `PathResolver::resolve_url` percent-encodes every
    // segment (it delegates to `output_url::pinned_url`), so a cover named
    // `封面.jpg` arrives here as `%E5%B0%81%E9%9D%A2.jpg`. Joining that onto
    // `source_root` verbatim looks for a file whose name is literally the
    // escape sequence, misses, and silently drops the card's dominant colour.
    // Decode back to the on-disk name before touching the filesystem.
    let decoded = moss_core::resolve::fuzzy_path::percent_decode_path(cover_url);
    let clean = decoded.strip_prefix('/').unwrap_or(&decoded);

    if let Some(thumb) = asset_paths::to_thumb_if_video(clean) {
        // Video thumbnails only exist in the build output (FFmpeg writes
        // them there); never fall back to source.
        return Some(output_root.join(thumb));
    }

    let source_path = source_root.join(clean);
    if source_path.exists() {
        Some(source_path)
    } else {
        Some(output_root.join(clean))
    }
}

/// Extracts the dominant color from an image file, darkened for white text readability.
///
/// Algorithm:
/// 1. Resize image to 50×50 for speed
/// 2. Compute average RGB across all pixels
/// 3. Convert to HSL, keeping hue and saturation
/// 4. Reduce lightness until WCAG AA contrast ratio ≥ 4.5:1 against white
///
/// # Returns
/// * `Some(String)` - HSLA color string like "hsla(200, 45%, 25%, 1)"
/// * `None` - If the image cannot be loaded or processed
pub fn extract_dominant_color(image_path: &Path) -> Option<String> {
    // Content-sniffed, not extension-only: a file whose extension lies about
    // its format (a PNG saved as `x.jpg`) still decodes, instead of silently
    // returning `None` here and losing the card's background color.
    let img = crate::build::media::decode::sniff_decode(image_path).ok()?;

    let img = img.resize(50, 50, image::imageops::FilterType::Nearest);
    let rgb = img.to_rgb8();

    let (mut r_sum, mut g_sum, mut b_sum) = (0u64, 0u64, 0u64);
    let mut count = 0u64;

    for pixel in rgb.pixels() {
        r_sum += pixel[0] as u64;
        g_sum += pixel[1] as u64;
        b_sum += pixel[2] as u64;
        count += 1;
    }

    if count == 0 {
        return None;
    }

    let r = (r_sum / count) as u8;
    let g = (g_sum / count) as u8;
    let b = (b_sum / count) as u8;

    Some(darkened_hsla(r, g, b))
}

/// Normalize a cached `MediaMetadata.dominant_color` value into a cover
/// background color (WCAG-AA contrast against white text, full saturation).
///
/// Used for card content bands. Scan stores two formats:
/// - Image scan → raw `#RRGGBB` average color. Needs WCAG darkening.
/// - Video scan → already-darkened `hsla(...)`. Pass through unchanged.
///
/// Returns `None` for unrecognized inputs.
pub fn prepare_cover_color(input: &str) -> Option<String> {
    prepare_background_color_inner(input, 1.0)
}

/// Normalize a cached `MediaMetadata.dominant_color` into a muted cover
/// background color (WCAG-AA contrast against white text, saturation × 0.8).
///
/// Used for hero mobile backgrounds where the color spans the full viewport
/// width. The 0.8 saturation multiplier softens vivid hues so the block
/// reads as atmospheric rather than garish.
///
/// Input formats and passthrough rules: same as `prepare_cover_color`.
/// Note: already-processed `hsla(...)` inputs (video scan path) pass through
/// unchanged — `sat_mult` is not applied to them.
pub fn prepare_cover_color_muted(input: &str) -> Option<String> {
    prepare_background_color_inner(input, 0.8)
}

/// Shared implementation for `prepare_cover_color` and
/// `prepare_cover_color_muted`. `sat_mult` is multiplied against the HSL
/// saturation before darkening (1.0 = full saturation for cards, 0.8 =
/// slightly desaturated for hero mobile backgrounds).
///
/// Already-processed HSL/HSLA/RGB/RGBA strings pass through unchanged
/// (idempotent; avoids double-darkening video scan results).
/// NOTE: this means the sat_mult is silently ignored for video-scanned
/// covers (which are stored as `hsla(...)` already). This is a known
/// limitation — image-scanned covers (#RRGGBB) do receive sat_mult.
fn prepare_background_color_inner(input: &str, sat_mult: f32) -> Option<String> {
    let trimmed = input.trim();
    if trimmed.is_empty() {
        return None;
    }

    // Already-darkened HSL/HSLA from the video path: trust scan, don't
    // re-darken. (rgb()/rgba() aren't produced by any scan path today;
    // treat them defensively the same way.) Tight match on the function
    // forms — `linear-gradient(...)` and similar starting with "rgb" or
    // "hsl" prefixes won't false-match.
    if trimmed.starts_with("hsl(")
        || trimmed.starts_with("hsla(")
        || trimmed.starts_with("rgb(")
        || trimmed.starts_with("rgba(")
    {
        return Some(trimmed.to_string());
    }

    if let Some(hex) = trimmed.strip_prefix('#') {
        let (r, g, b) = parse_hex_rgb(hex)?;
        let (h, s, l) = rgb_to_hsl(r, g, b);
        let s = s * sat_mult;
        let l = darken_for_contrast(h, s, l);
        return Some(format!("hsla({}, {:.0}%, {:.0}%, 1)", h as i32, s * 100.0, l * 100.0));
    }

    None
}


/// Parse a 3- or 6-digit hex color (without the leading `#`) into RGB bytes.
///
/// Matched on characters, not bytes: an author can write anything in a colour
/// field, and `hex.len()` counting bytes made `"#é1"` (3 bytes, 2 chars) look
/// like a 3-digit hex colour whose first slice cut `é` in half.
fn parse_hex_rgb(hex: &str) -> Option<(u8, u8, u8)> {
    fn digit(c: char) -> Option<u8> {
        c.to_digit(16).map(|v| v as u8)
    }
    let chars: Vec<char> = hex.chars().collect();
    match chars.as_slice() {
        // #RGB → expand each nibble to a byte (0xR * 0x11 == 0xRR).
        &[r, g, b] => Some((digit(r)? * 0x11, digit(g)? * 0x11, digit(b)? * 0x11)),
        &[r1, r2, g1, g2, b1, b2] => Some((
            digit(r1)? * 0x10 + digit(r2)?,
            digit(g1)? * 0x10 + digit(g2)?,
            digit(b1)? * 0x10 + digit(b2)?,
        )),
        _ => None,
    }
}

/// Compute WCAG 2.x relative luminance from linear RGB.
///
/// Formula: L = 0.2126 * R + 0.7152 * G + 0.0722 * B
/// where R, G, B are linearized (gamma-decoded) sRGB values.
fn relative_luminance(r: f32, g: f32, b: f32) -> f32 {
    fn linearize(c: f32) -> f32 {
        if c <= 0.04045 {
            c / 12.92
        } else {
            ((c + 0.055) / 1.055).powf(2.4)
        }
    }
    0.2126 * linearize(r) + 0.7152 * linearize(g) + 0.0722 * linearize(b)
}

/// Is this image light enough that white overlay text needs a stronger scrim?
///
/// Takes a raw scan-cached `dominant_color` (`#RRGGBB` from image scan, or an
/// already-processed `hsla(...)` from video scan) and reports whether its
/// relative luminance is high. A cover that is mostly pale — a watercolour
/// wash, snow, an overexposed sky, a designed pastel gradient — cannot carry
/// white type over the default scrim, while the same scrim over a mid-tone or
/// dark image is already more than enough.
/// `.moss-hero[data-hero-tone="light"]` keys off this.
///
/// What "light" MEANS in CSS changed on 2026-08-09: it used to select a
/// heavier scrim so white type survived, and now it removes the scrim and sets
/// the text dark instead. The predicate is unchanged — the question "is this
/// image too pale for white type" has the same answer either way — but the
/// threshold's justification moved with it. It is no longer "where the default
/// gradient stops reaching 4.5:1", because there is no longer a gradient on
/// this side of it; it is the crossover where dark type on the image beats
/// white type on a scrim. 0.4 sits comfortably inside both readings, and the
/// fifteen real covers measured against it split 11/4 with nothing nearer than
/// 0.27 on one side and 0.55 on the other.
///
/// Video-scan colours are already WCAG-darkened, so they never trip it —
/// correct, since that darkening means white text already has contrast.
///
/// Returns `None` when the colour cannot be parsed (caller emits no attribute,
/// so the hero keeps white type over the default scrim).
pub fn is_light_cover(raw_dominant_color: &str) -> Option<bool> {
    // `parse_hex_rgb` takes the digits only — the `#` is the caller's to strip.
    let hex = raw_dominant_color.trim().strip_prefix('#')?;
    let (r, g, b) = parse_hex_rgb(hex)?;
    let lum = relative_luminance(r as f32 / 255.0, g as f32 / 255.0, b as f32 / 255.0);
    Some(lum > 0.4)
}

/// WCAG 2.x contrast ratio between two relative luminances.
fn contrast_ratio(l1: f32, l2: f32) -> f32 {
    let (lighter, darker) = if l1 > l2 { (l1, l2) } else { (l2, l1) };
    (lighter + 0.05) / (darker + 0.05)
}

/// Convert HSL to RGB (sRGB, 0.0–1.0 range).
fn hsl_to_rgb(h: f32, s: f32, l: f32) -> (f32, f32, f32) {
    if s.abs() < f32::EPSILON {
        return (l, l, l);
    }

    let q = if l < 0.5 {
        l * (1.0 + s)
    } else {
        l + s - l * s
    };
    let p = 2.0 * l - q;
    let h = h / 360.0;

    fn hue_to_rgb(p: f32, q: f32, mut t: f32) -> f32 {
        if t < 0.0 { t += 1.0; }
        if t > 1.0 { t -= 1.0; }
        if t < 1.0 / 6.0 {
            p + (q - p) * 6.0 * t
        } else if t < 0.5 {
            q
        } else if t < 2.0 / 3.0 {
            p + (q - p) * (2.0 / 3.0 - t) * 6.0
        } else {
            p
        }
    }

    (
        hue_to_rgb(p, q, h + 1.0 / 3.0),
        hue_to_rgb(p, q, h),
        hue_to_rgb(p, q, h - 1.0 / 3.0),
    )
}

/// Reduce HSL lightness until WCAG AA contrast ≥ 4.5:1 against white.
///
/// Keeps hue and saturation, only reduces lightness. Binary search for
/// the highest lightness that still meets the contrast threshold.
fn darken_for_contrast(h: f32, s: f32, l: f32) -> f32 {
    let white_lum = 1.0; // relative luminance of white

    // Check if the color already passes
    let (r, g, b) = hsl_to_rgb(h, s, l);
    let lum = relative_luminance(r, g, b);
    if contrast_ratio(white_lum, lum) >= 4.5 {
        // Apply the same integer-percent rounding guard as the binary-search
        // path: `{:.0}%` formatting could round l up by 1%, which may push a
        // borderline-passing color across the 4.5:1 boundary after a parse
        // round-trip. Floor instead of round when that happens.
        let rounded_l = (l * 100.0).round() / 100.0;
        let (rr, gg, bb) = hsl_to_rgb(h, s, rounded_l);
        return if contrast_ratio(white_lum, relative_luminance(rr, gg, bb)) < 4.5 {
            ((l * 100.0).floor() / 100.0).max(0.0)
        } else {
            l
        };
    }

    // Binary search: find the highest L that gives ≥ 4.5:1 contrast
    let mut lo = 0.0_f32;
    let mut hi = l;
    for _ in 0..20 {
        let mid = (lo + hi) / 2.0;
        let (r, g, b) = hsl_to_rgb(h, s, mid);
        let lum = relative_luminance(r, g, b);
        if contrast_ratio(white_lum, lum) >= 4.5 {
            lo = mid; // Can go lighter
        } else {
            hi = mid; // Too light, go darker
        }
    }

    // Guard against the nearest-integer-percent rounding crossing the WCAG
    // boundary. `{:.0}%` formatting rounds `lo * 100` to the nearest integer;
    // if that integer is 1 higher than `lo * 100` (e.g. 46.53 → 47), the
    // formatted value can become slightly too light after a round-trip parse.
    // Back off by 1% if the rounded form would fail 4.5:1.
    let rounded_l = (lo * 100.0).round() / 100.0;
    let (rr, gg, bb) = hsl_to_rgb(h, s, rounded_l);
    if contrast_ratio(white_lum, relative_luminance(rr, gg, bb)) < 4.5 {
        ((lo * 100.0).floor() / 100.0).max(0.0)
    } else {
        lo
    }
}

/// Converts RGB values to HSL.
fn rgb_to_hsl(r: u8, g: u8, b: u8) -> (f32, f32, f32) {
    let r = r as f32 / 255.0;
    let g = g as f32 / 255.0;
    let b = b as f32 / 255.0;

    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    let l = (max + min) / 2.0;

    if (max - min).abs() < f32::EPSILON {
        return (0.0, 0.0, l);
    }

    let d = max - min;
    let s = if l > 0.5 {
        d / (2.0 - max - min)
    } else {
        d / (max + min)
    };

    let h = if (max - r).abs() < f32::EPSILON {
        let mut h = (g - b) / d;
        if g < b {
            h += 6.0;
        }
        h
    } else if (max - g).abs() < f32::EPSILON {
        (b - r) / d + 2.0
    } else {
        (r - g) / d + 4.0
    };

    (h * 60.0, s, l)
}

/// Format an RGB color as the WCAG-darkened `hsla(...)` card-band string.
/// Single formatting point for every ladder rung that starts from raw RGB.
fn darkened_hsla(r: u8, g: u8, b: u8) -> String {
    let (h, s, l) = rgb_to_hsl(r, g, b);
    let l = darken_for_contrast(h, s, l);
    format!("hsla({}, {:.0}%, {:.0}%, 1)", h as i32, s * 100.0, l * 100.0)
}

/// Extract a card color from a local webpage cover (rungs 2–3 of the
/// cover-color ladder): `<meta name="theme-color">` first, then a tightly
/// scoped static `html`/`body` background scan. Returns the WCAG-darkened
/// `hsla(...)` string, or `None` when the page declares no usable color
/// (callers fall through to the iframe dark default).
pub(crate) fn extract_webpage_color(html_path: &Path) -> Option<String> {
    let html = std::fs::read_to_string(html_path).ok()?;
    let (r, g, b) = scan_webpage_color(&html)?;
    Some(darkened_hsla(r, g, b))
}

/// Scan webpage HTML for a declared color. Pure function — no I/O, and the
/// page is NEVER rendered (a JS-painted canvas is statically invisible by
/// design; see the spec's rejected-approaches section).
///
/// Precedence:
/// theme-color meta (media-less preferred, else first) → `body` → `html`;
/// within an element a `style=` attr beats `<style>` rules; among `<style>`
/// declarations for the same element the last one wins (cascade order).
pub(crate) fn scan_webpage_color(html: &str) -> Option<(u8, u8, u8)> {
    use scraper::{Html, Selector};
    let doc = Html::parse_document(html);

    // Rung 2: theme-color meta. Choose ONE meta (media-less preferred —
    // media'd entries are light/dark pairs and the band gets darkened
    // anyway, so a deterministic pick is what matters), then parse it.
    // A chosen-but-unparseable content falls through to rung 3.
    let meta_sel = Selector::parse("meta[name][content]").unwrap();
    let metas: Vec<_> = doc
        .select(&meta_sel)
        .filter(|m| {
            m.value()
                .attr("name")
                .is_some_and(|n| n.eq_ignore_ascii_case("theme-color"))
        })
        .collect();
    let chosen = metas
        .iter()
        .find(|m| m.value().attr("media").is_none())
        .or_else(|| metas.first());
    if let Some(meta) = chosen {
        if let Some(c) = meta.value().attr("content").and_then(parse_css_color) {
            return Some(c);
        }
    }

    // Rung 3: static background scan, scoped to html/body.
    let style_attr_bg = |sel: &str| -> Option<(u8, u8, u8)> {
        let s = Selector::parse(sel).unwrap();
        doc.select(&s).next()?.value().attr("style").and_then(scan_decls_for_background)
    };
    let body_attr = style_attr_bg("body");
    let html_attr = style_attr_bg("html");

    let (mut body_css, mut html_css) = (None, None);
    let style_sel = Selector::parse("style").unwrap();
    for st in doc.select(&style_sel) {
        let css: String = st.text().collect();
        scan_style_rules(&css, &mut body_css, &mut html_css);
    }

    body_attr.or(body_css).or(html_attr).or(html_css)
}

/// Scan a `<style>` block for `background(-color)` declarations on rules
/// whose selector list contains ONLY the simple selectors `body` / `html`.
/// Anything fancier (classes, combinators, `@media` nesting — whose brace
/// structure this naive `}`-splitter mis-chunks into non-matching selector
/// text) is skipped, deliberately: this is NOT a CSS cascade, and every
/// unsupported form falls through the ladder. Later rules overwrite
/// earlier ones (last-wins).
fn scan_style_rules(
    css: &str,
    body_bg: &mut Option<(u8, u8, u8)>,
    html_bg: &mut Option<(u8, u8, u8)>,
) {
    for chunk in css.split('}') {
        let Some((sels, decls)) = chunk.split_once('{') else { continue };
        let (mut body, mut html, mut only_simple) = (false, false, true);
        for sel in sels.split(',') {
            match sel.trim().to_ascii_lowercase().as_str() {
                "body" => body = true,
                "html" => html = true,
                "" => {}
                _ => only_simple = false,
            }
        }
        if !only_simple || (!body && !html) {
            continue;
        }
        if let Some(c) = scan_decls_for_background(decls) {
            if body {
                *body_bg = Some(c);
            }
            if html {
                *html_bg = Some(c);
            }
        }
    }
}

/// Scan a `;`-separated declaration list for `background` /
/// `background-color` whose value is a SINGLE color literal. Shorthand
/// values with extra parts (`black url(x)`), gradients, `var()`, and
/// `transparent` fail `parse_css_color` and are skipped. Last wins.
fn scan_decls_for_background(decls: &str) -> Option<(u8, u8, u8)> {
    let mut found = None;
    for decl in decls.split(';') {
        let Some((prop, value)) = decl.split_once(':') else { continue };
        let prop = prop.trim().to_ascii_lowercase();
        if prop == "background" || prop == "background-color" {
            if let Some(c) = parse_css_color(value.trim()) {
                found = Some(c);
            }
        }
    }
    found
}

/// Parse a CSS color literal into RGB bytes.
///
/// Accepts `#hex` (3- and 6-digit), `rgb()`/`rgba()` (commas, spaces, or
/// `/`-alpha syntax; numeric or percentage components), `hsl()`/`hsla()`,
/// and a table of common named colors (CSS basic-16 + frequent extended
/// names). Unknown names and non-color values (gradients, `url()`, `var()`,
/// `transparent`) return `None` — callers fall through to the next signal
/// in the cover-color ladder, so a miss is always benign.
/// Alpha components are parsed but ignored (cover bands are opaque).
pub(crate) fn parse_css_color(input: &str) -> Option<(u8, u8, u8)> {
    let v = input.trim();
    if let Some(hex) = v.strip_prefix('#') {
        return parse_hex_rgb(hex);
    }
    let lower = v.to_ascii_lowercase();
    if let Some(inner) = lower.strip_prefix("rgba(").or_else(|| lower.strip_prefix("rgb(")) {
        let inner = inner.strip_suffix(')')?;
        let toks = split_color_args(inner);
        if toks.len() < 3 {
            return None;
        }
        let r = parse_rgb_component(toks[0])?;
        let g = parse_rgb_component(toks[1])?;
        let b = parse_rgb_component(toks[2])?;
        return Some((r, g, b));
    }
    if let Some(inner) = lower.strip_prefix("hsla(").or_else(|| lower.strip_prefix("hsl(")) {
        let inner = inner.strip_suffix(')')?;
        let toks = split_color_args(inner);
        if toks.len() < 3 {
            return None;
        }
        let h = toks[0].trim_end_matches("deg").parse::<f32>().ok()?.rem_euclid(360.0);
        let s = parse_percent(toks[1])?;
        let l = parse_percent(toks[2])?;
        let (r, g, b) = hsl_to_rgb(h, s, l);
        return Some((
            (r * 255.0).round() as u8,
            (g * 255.0).round() as u8,
            (b * 255.0).round() as u8,
        ));
    }
    NAMED_COLORS
        .iter()
        .find(|(name, _)| *name == lower)
        .map(|(_, rgb)| (((rgb >> 16) & 0xFF) as u8, ((rgb >> 8) & 0xFF) as u8, (rgb & 0xFF) as u8))
}

/// Split `rgb()`/`hsl()` arguments on commas, whitespace, and the modern
/// `/`-alpha separator, dropping empties — accepts both `rgb(1, 2, 3)` and
/// `rgb(1 2 3 / 0.5)` forms.
fn split_color_args(inner: &str) -> Vec<&str> {
    inner
        .split(|c: char| c == ',' || c == '/' || c.is_whitespace())
        .filter(|t| !t.is_empty())
        .collect()
}

/// Parse one rgb() component: `0`–`255` numeric or `0%`–`100%` percentage.
fn parse_rgb_component(tok: &str) -> Option<u8> {
    if let Some(p) = tok.strip_suffix('%') {
        let f = p.parse::<f32>().ok()?;
        return Some((f.clamp(0.0, 100.0) * 255.0 / 100.0).round() as u8);
    }
    let f = tok.parse::<f32>().ok()?;
    Some(f.clamp(0.0, 255.0).round() as u8)
}

/// Parse a percentage token (`"45%"`) into 0.0–1.0.
fn parse_percent(tok: &str) -> Option<f32> {
    let p = tok.strip_suffix('%')?;
    Some((p.parse::<f32>().ok()? / 100.0).clamp(0.0, 1.0))
}

