    /// A minimal valid index. Tests mutate the pieces they are about.
    fn index_json(serial: u64, entries: &str) -> String {
        format!(r#"{{"schema_version":1,"serial":{serial},"entries":[{entries}]}}"#)
    }

    fn entry(id: &str, entry_type: &str) -> String {
        format!(
            r#"{{"type":"{entry_type}","id":"{id}","display_name":"{id}","version":"1.0.0",
                 "download_url":"https://example.invalid/{id}.zip","sha256":"aa"}}"#
        )
    }

