#!/usr/bin/env node
// gen-architecture-diagrams — keep the Mermaid diagrams in ARCHITECTURE.md true to the code.
//
//   node scripts/gen-architecture-diagrams.mjs          rewrite the generated crate graph
//   node scripts/gen-architecture-diagrams.mjs --check  exit 1 on drift or on a name the code lacks
//
// The crate graph is generated from `cargo metadata` between the marker
// comments: a crate list drawn by hand is a second copy of what the Cargo.toml
// files already say, and nothing would notice it drift.
//
// A hand-drawn diagram marks a node whose label names code with a Mermaid
// class, and the first line of that label must exist:
//   :::crate   a workspace crate
//   :::path    a tracked, repo-relative file or directory
//   :::symbol  a Rust or TypeScript item defined under crates/ or packages/
// Unmarked nodes, edge labels and subgraph titles are prose and are not
// checked. Every block must also parse in pele, the renderer the diagrams are
// drawn for, read through its own parse().

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'pele';

const TAG = 'gen-architecture-diagrams';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOC = path.join(ROOT, 'ARCHITECTURE.md');
const START = '<!-- architecture:crate-graph:start -->';
const END = '<!-- architecture:crate-graph:end -->';
const CODE_CLASSES = ['crate', 'path', 'symbol'];

const nodeId = (name) => name.replace(/[^A-Za-z0-9]/g, '_');

/** The generated block, markers included: workspace crates and their normal edges, from `cargo metadata --no-deps`. */
export function renderCrateGraph(meta) {
  const crates = meta.packages.map((p) => p.name).sort();
  const edges = meta.packages.flatMap((p) =>
    p.dependencies
      .filter((d) => d.kind === null && crates.includes(d.name))
      .map((d) => `    ${nodeId(p.name)} --> ${nodeId(d.name)}`),
  );
  return [
    START,
    '<!-- Generated by `node scripts/gen-architecture-diagrams.mjs` from `cargo metadata`; do not hand-edit. -->',
    '',
    '```mermaid',
    '---',
    'title: The crates. An arrow points at what a crate depends on.',
    '---',
    'flowchart LR',
    ...crates.map((c) => `    ${nodeId(c)}["${c}"]:::crate`),
    ...edges.sort(),
    '```',
    '',
    END,
  ].join('\n');
}

export function replaceGenerated(doc, block) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${TAG}: ARCHITECTURE.md has no ${START} … ${END} block`);
  return doc.slice(0, a) + block + doc.slice(b + END.length);
}

/** `{ kind, name }` for every marked node in every Mermaid block, or a parse error. */
export function markedNames(md) {
  const out = [];
  const re = /^```mermaid[ \t]*\n([\s\S]*?)^```/gm;
  for (let m; (m = re.exec(md)); ) {
    const line = md.slice(0, m.index).split('\n').length;
    let model;
    try {
      model = parse(m[1]);
    } catch (e) {
      out.push({ line, error: e.message });
      continue;
    }
    if (!(model.nodes instanceof Map)) continue;
    for (const node of model.nodes.values()) {
      const kind = (node.classes ?? []).find((c) => CODE_CLASSES.includes(c));
      if (kind) out.push({ line, kind, name: String(node.text ?? node.id).split(/<br\s*\/?>/i)[0].trim() });
    }
  }
  return out;
}

export function makeResolver(crateNames, root = ROOT) {
  const git = (args) => spawnSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return ({ kind, name }) => {
    if (kind === 'crate') return crateNames.includes(name);
    if (kind === 'path') return git(['--literal-pathspecs', 'ls-files', '--', name]).stdout?.trim() !== '' && !name.split('/').includes('..');
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) return false;
    // A fixed-string search finds the candidate files on any git; the definition
    // is matched in JavaScript, since Apple's git grep has no `\s` or `\b`.
    const def = new RegExp(`\\b(struct|enum|trait|type|fn|mod|const|static|interface|class|function)\\s+${name}\\b`);
    const files = git(['grep', '-lF', '-e', name, '--', 'crates/*.rs', 'packages/*.ts']).stdout ?? '';
    return files.split('\n').filter(Boolean).some((f) => def.test(fs.readFileSync(path.join(root, f), 'utf8')));
  };
}

export function problemsIn(md, resolves) {
  return markedNames(md).flatMap((n) => {
    if (n.error) return [`ARCHITECTURE.md:${n.line}: pele cannot parse this diagram: ${n.error}`];
    return resolves(n) ? [] : [`ARCHITECTURE.md:${n.line}: :::${n.kind} "${n.name}" does not exist in the code`];
  });
}

function main() {
  const check = process.argv.includes('--check');
  const res = spawnSync('cargo', ['metadata', '--format-version', '1', '--no-deps', '--offline'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  });
  if (res.status !== 0) {
    console.error(`${TAG}: cargo metadata failed\n${res.stderr ?? res.error}`);
    process.exit(1);
  }
  const meta = JSON.parse(res.stdout);
  const doc = fs.readFileSync(DOC, 'utf8');
  const next = replaceGenerated(doc, renderCrateGraph(meta));
  const problems = [];
  if (next !== doc) {
    if (check) problems.push(`ARCHITECTURE.md: the crate graph is stale; run node scripts/${TAG}.mjs`);
    else fs.writeFileSync(DOC, next);
  }
  const crates = meta.packages.map((p) => p.name);
  problems.push(...problemsIn(next, makeResolver(crates)));
  for (const p of problems) console.error(`FAIL ${p}`);
  console.log(`${TAG}: ${problems.length ? 'RED' : 'GREEN'}`);
  process.exit(problems.length ? 1 : 0);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main();
}
